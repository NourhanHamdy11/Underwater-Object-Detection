# Extract the confusion matrix from the results
confusion_matrix = results.confusion_matrix  # Confusion matrix is stored in `results.box.confusion_matrix`

# Initialize variables
total_tp = 0
total_instances = 0
print(confusion_matrix.matrix)

# Loop through the diagonal of the confusion matrix for true positives
for class_idx in range(len(confusion_matrix.matrix)-1):
    tp = confusion_matrix.matrix[class_idx, class_idx]  # True positives for the current class
    total_instances_class = 0
    for i in range(len(confusion_matrix.matrix)):
      total_instances_class += confusion_matrix.matrix[i][class_idx]
    # total_instances_class = confusion_matrix.matrix[:][class_idx].sum()  # Total ground truth instances for the class
    total_tp += tp
    total_instances += total_instances_class

    print(f"Class {class_idx}: TP = {tp}, Total Instances = {total_instances_class}")

# Calculate accuracy
accuracy = total_tp / total_instances if total_instances > 0 else 0

# Print results
print(f"\nTotal True Positives (TP): {total_tp}")
print(f"Total Instances: {total_instances}")
print(f"Accuracy: {accuracy * 100:.2f}%")