# Step 6: Define Class Mapping
class_map = {
    "Fish": 0,
    "Crab": 1,
    "Human": 2,
    "Trash": 3,
    "Jelly-fish": 4,
    "Coral-Reef": 5,
    "Fish-Group": 6
}

import os
import glob
import cv2

# Function to convert quadrilateral to YOLO bounding box
def convert_to_yolo_format(img_width, img_height, points):
    x_coords = [points[0], points[2], points[4], points[6]]
    y_coords = [points[1], points[3], points[5], points[7]]

    xmin, xmax = min(x_coords), max(x_coords)
    ymin, ymax = min(y_coords), max(y_coords)

    x_center = (xmin + xmax) / 2 / img_width
    y_center = (ymin + ymax) / 2 / img_height
    width = (xmax - xmin) / img_width
    height = (ymax - ymin) / img_height

    return x_center, y_center, width, height

# Paths to the dataset
data_splits = ['train', 'valid', 'test']
base_path = '/content/underwater_dataset'

for split in data_splits:
    images_path = os.path.join(base_path, split, 'images')
    annotations_path = os.path.join(base_path, split, 'labelTxt')
    labels_output_path = os.path.join(base_path, split, 'labels')

    os.makedirs(labels_output_path, exist_ok=True)  # Ensure output directory exists

    annotation_files = glob.glob(os.path.join(annotations_path, '*.txt'))

    for annotation_file in annotation_files:
        # Get corresponding image path
        img_name = os.path.basename(annotation_file).replace('.txt', '.jpg')
        img_path = os.path.join(images_path, img_name)

        if not os.path.exists(img_path):
            print(f"Image {img_path} not found, skipping...")
            continue

        # Load image to get dimensions
        img = cv2.imread(img_path)
        img_height, img_width, _ = img.shape

        # Read annotation file
        with open(annotation_file, 'r') as f:
            lines = f.readlines()

        yolo_annotations = []
        for line in lines:
            values = line.strip().split()
            points = list(map(float, values[:8]))  # First 8 values are points
            class_label = int(class_map[values[8]])  # Class label

            # Convert to YOLO format
            x_center, y_center, width, height = convert_to_yolo_format(img_width, img_height, points)
            yolo_annotations.append(f"{class_label} {x_center} {y_center} {width} {height}")

        # Write YOLO annotations to the corresponding label file
        label_file = os.path.join(labels_output_path, os.path.basename(annotation_file))
        with open(label_file, 'w') as f:
            f.write('\n'.join(yolo_annotations))

